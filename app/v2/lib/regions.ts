export const REGIONS: Region[] = RAW.split(/[|\n]/).map((s) => {
  const parts = s.trim().split(" ");
  const lon = Number(parts.pop());
  const lat = Number(parts.pop());
  return { name: parts.join(" "), lat, lon };
});

/** 글자로 찾기: "홍" → 충남 홍성, 강원 홍천 */
export function searchRegions(q: string): Region[] {
  const t = q.replace(/\s+/g, "");
  if (!t) return [];
  return REGIONS.filter((r) => r.name.replace(/\s+/g, "").includes(t)).slice(0, 8);
}

/** 휴대폰 위치에서 가장 가까운 시·군 */
export function nearestRegion(lat: number, lon: number): Region {
  let best = REGIONS[0];
  let bestD = Infinity;
  for (const r of REGIONS) {
    const d = (r.lat - lat) ** 2 + ((r.lon - lon) * Math.cos((lat * Math.PI) / 180)) ** 2;
    if (d < bestD) {
      bestD = d;
      best = r;
    }
  }
  return best;
}
