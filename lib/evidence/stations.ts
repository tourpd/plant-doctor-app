export function stationFor(region: string): { id: number; name: string; exact: boolean } | null {
  const r = String(region || "");
  const words = r.replace(/(특별자치도|특별자치시|특별시|광역시|도)\b/g, " ").split(/\s+/).map((w) => w.replace(/(시|군|구)$/, "")).filter(Boolean);
  for (const w of words.slice(1).concat(words)) {
    if (ASOS[w]) return { id: ASOS[w], name: w, exact: true };
    if (NEAR[w]) return { id: ASOS[NEAR[w]], name: NEAR[w], exact: false };
  }
  for (const [k, v] of Object.entries(SIDO_DEFAULT)) if (r.includes(k)) return { id: ASOS[v], name: v, exact: false };
  return null;
}
